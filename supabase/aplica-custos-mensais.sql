-- ============================================================================
-- Custos mensais editáveis no painel do admin (#473)
--
-- O bloco "O Lupa já se paga?" (#471) comparava a receita com dois custos
-- escritos no código. Agora o admin acrescenta, edita e remove custos na
-- tela — contador, aluguel, o que vier —, e eles moram aqui.
--
-- A tabela nasce com os mesmos dois custos de antes, e só se estiver vazia:
-- rodar de novo não duplica, nem desfaz o que o admin já editou.
--
-- **Rode antes do deploy**: o código novo lê esta tabela, e sem ela o
-- painel do admin responde "indisponível". Seguro de rodar mais de uma vez.
-- ============================================================================

begin;

create table if not exists custos_mensais (
  id             uuid primary key default gen_random_uuid(),
  -- A ordem de cobertura é a de cadastro: a receita paga o primeiro custo
  -- inteiro antes de chegar ao segundo.
  ordem          bigint generated by default as identity,
  nome           text not null check (char_length(btrim(nome)) between 2 and 60),
  -- Em centavos, por mês. Até R$ 100.000,00: acima disso é engano.
  valor_centavos integer not null
                 check (valor_centavos between 1 and 10000000),
  criado_em      timestamptz not null default now(),
  atualizado_em  timestamptz not null default now()
);

drop trigger if exists custos_mensais_atualizado_em on custos_mensais;
create trigger custos_mensais_atualizado_em
  before update on custos_mensais
  for each row execute function tocar_atualizado_em();

alter table custos_mensais enable row level security;

do $$
begin
  if not exists (select 1 from custos_mensais) then
    insert into custos_mensais (nome, valor_centavos) values ('Supabase Pro', 13300);
    insert into custos_mensais (nome, valor_centavos) values ('Vercel Pro', 10700);
  end if;
end $$;

-- Dado da empresa: nenhuma das chaves públicas lê nem escreve. É `revoke
-- all` porque o Supabase concede tudo às duas chaves em toda tabela nova
-- (#421), e o revoke geral do fim do `schema.sql` não roda aqui.
revoke all on custos_mensais from anon, authenticated;

commit;
